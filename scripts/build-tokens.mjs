import {
  mkdir,
  readdir,
  readFile,
  writeFile,
} from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageDirectory = join(
  dirname(fileURLToPath(import.meta.url)),
  '..'
);
const themesDirectory = join(packageDirectory, 'themes');
const outputDirectory = join(packageDirectory, 'dist');
const modes = ['light', 'dark'];

const files = (await readdir(themesDirectory))
  .filter((file) => file.endsWith('.json'))
  .sort((left, right) => left.localeCompare(right));

if (files.length === 0) {
  throw new Error('Add at least one JSON file to themes/.');
}

const themes = await Promise.all(
  files.map(async (file) =>
    JSON.parse(
      await readFile(join(themesDirectory, file), 'utf8')
    )
  )
);
const tokenNames = Object.keys(
  themes[0]?.modes?.light ?? {}
).sort((left, right) => left.localeCompare(right));

const themeIdSet = new Set();
for (const theme of themes) {
  if (
    typeof theme.id !== 'string' ||
    !/^[a-z][a-z0-9-]*$/.test(theme.id)
  ) {
    throw new Error(
      `Theme id must be kebab-case: ${JSON.stringify(theme.id)}`
    );
  }
  if (themeIdSet.has(theme.id)) {
    throw new Error(`Duplicate theme id: ${theme.id}`);
  }
  themeIdSet.add(theme.id);

  if (
    typeof theme.label !== 'string' ||
    !Array.isArray(theme.swatches) ||
    theme.swatches.length === 0
  ) {
    throw new Error(
      `Theme ${theme.id} requires label and non-empty swatches.`
    );
  }

  for (const mode of modes) {
    const tokens = theme.modes?.[mode];
    if (tokens === undefined) {
      throw new Error(
        `Theme ${theme.id} is missing ${mode} mode.`
      );
    }
    const modeTokenNames = Object.keys(tokens).sort(
      (left, right) => left.localeCompare(right)
    );
    if (
      modeTokenNames.join('\n') !== tokenNames.join('\n')
    ) {
      throw new Error(
        `Theme ${theme.id}/${mode} must define the same tokens as every other theme mode.`
      );
    }
    for (const token of tokenNames) {
      if (
        typeof tokens[token] !== 'string' ||
        !/^#[0-9a-f]{3,8}$/i.test(tokens[token])
      ) {
        throw new Error(
          `Theme ${theme.id}/${mode} has an invalid ${token} token.`
        );
      }
    }
  }
}

const css = [
  '/* This file is generated by pnpm build. Do not edit directly. */',
  '',
];
for (const theme of themes) {
  for (const mode of modes) {
    css.push(
      `:where(:root, [data-theme-base=\"${mode}\"][data-theme-color=\"${theme.id}\"]) {`
    );
    for (const token of tokenNames) {
      css.push(
        `  --color-${token}: ${theme.modes[mode][token]};`
      );
    }
    css.push('}', '');
  }
}

const manifest = {
  themes: themes.map(({ id, label, swatches }) => ({
    id,
    label,
    swatches,
    modes,
  })),
};
const themeIds = themes.map(({ id }) => id);
const themeApi = [
  '// This file is generated by pnpm build. Do not edit directly.',
  `export const themeIds = ${JSON.stringify(themeIds)};`,
  `export const themeModes = ${JSON.stringify(modes)};`,
  `export const themeOptions = ${JSON.stringify(manifest.themes, null, 2)};`,
  `export const themes = ${JSON.stringify(themes, null, 2)};`,
  '',
  'export function getThemeTokens(themeId, mode) {',
  '  const theme = themes.find((candidate) => candidate.id === themeId);',
  '  if (theme === undefined) {',
  '    throw new Error(`Unknown theme: ${themeId}`);',
  '  }',
  '  return theme.modes[mode];',
  '}',
  '',
].join('\n');
const tuple = (values) =>
  `readonly [${values.map((value) => JSON.stringify(value)).join(', ')}]`;
const themeApiTypes = [
  '// This file is generated by pnpm build. Do not edit directly.',
  `export declare const themeIds: ${tuple(themeIds)};`,
  'export type ThemeId = (typeof themeIds)[number];',
  `export declare const themeModes: ${tuple(modes)};`,
  'export type ThemeMode = (typeof themeModes)[number];',
  `export type ThemeTokenName = ${tokenNames.map((token) => JSON.stringify(token)).join(' | ')};`,
  'export type ThemeTokens = Readonly<Record<ThemeTokenName, string>>;',
  'export interface ThemeOption {',
  '  readonly id: ThemeId;',
  '  readonly label: string;',
  '  readonly swatches: readonly string[];',
  '  readonly modes: readonly ThemeMode[];',
  '}',
  'export interface ThemeDefinition extends Omit<ThemeOption, "modes"> {',
  '  readonly modes: Readonly<Record<ThemeMode, ThemeTokens>>;',
  '}',
  'export declare const themeOptions: readonly ThemeOption[];',
  'export declare const themes: readonly ThemeDefinition[];',
  'export declare function getThemeTokens(themeId: ThemeId, mode: ThemeMode): ThemeTokens;',
  '',
].join('\n');

await mkdir(outputDirectory, { recursive: true });
await writeFile(
  join(outputDirectory, 'tokens.css'),
  `${css.join('\n')}\n`
);
await writeFile(
  join(outputDirectory, 'themes.json'),
  `${JSON.stringify(manifest, null, 2)}\n`
);
await writeFile(
  join(outputDirectory, 'themes.js'),
  themeApi
);
await writeFile(
  join(outputDirectory, 'themes.d.ts'),
  themeApiTypes
);
